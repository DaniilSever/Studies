import random

# tools
Matrix = list[list[int]]


def random_matrix(n: int, m: int, max_val: int) -> Matrix:
    return [[random.randrange(max_val) for _ in range(m)] for _ in range(n)]


def print_matrix(a: Matrix) -> None:
    for row in a:
        print(" ".join(f"{v:3d}" for v in row))


